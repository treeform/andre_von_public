proc openingFor*(spawnTile: int): Opening =
  ## Return the measured opening for one exact spawn tile.
  for opening in OpeningBook:
    if opening.spawnTile == spawnTile:
      return opening
  Opening(spawnTile: -1)

proc openingApplies*(scope: OpeningScope, spawnTile: int): bool =
  ## Report whether one scripted-opening scope contains this start.
  let opening = openingFor(spawnTile)
  if opening.spawnTile < 0:
    return false
  case scope
  of openingNone:
    false
  of openingAll:
    true
  of openingOptimized:
    opening.optimized
  of openingOceania:
    opening.mapName == "Oceania"
  of openingBlackSea:
    opening.mapName == "Black Sea"
  of openingPangaea:
    opening.mapName == "Pangaea"
  of openingWater:
    opening.mapName in ["Oceania", "Black Sea"]
