# Generates Primordial-loop Mage variants onto the v29 rules base.
import itertools, sys
base = open('trials/duelsharp.bas').read().split('\n')
head = '\n'.join(base[:217]); tail = '\n'.join(base[341:])

def mage(R, D, O, S, reserve):
    s = []
    a = s.append
    a("if isMage = 1 then")
    a("  ' Primordial loop. Variant: reset " + R + ", dig " + D + ", ooze " + O + ", second copy " + S + ", reserve " + str(reserve) + ".")
    a("  ' The Primordial attacks only at the end of a turn it has sat through,")
    a("  ' so a cycle is one attack turn and one reset turn: a Bouncer returns")
    a("  ' it to hand and the replay wipes every other board and heals it, and")
    a("  ' our played Bouncers come back to hand with that wipe.")
    a("  primHand = -1")
    a("  prim2Hand = -1")
    a("  bouncerHand = -1")
    a("  bouncers = 0")
    a("  planHand = -1")
    a("  shieldHand = -1")
    a("  oozeHand = -1")
    a("  i = 0")
    a("  while i < handSize")
    a("    if handKind(i) = 0 and handCost(i) = 8 then")
    a("      if primHand < 0 then")
    a("        primHand = i")
    a("      else")
    a("        prim2Hand = i")
    a("      end if")
    a("    end if")
    a("    if handKind(i) = 0 and handCost(i) = 1 and handToughness(i) = 1 then")
    a("      if bouncerHand < 0 then bouncerHand = i")
    a("      bouncers = bouncers + 1")
    a("    end if")
    a("    if handKind(i) = 2 and handCost(i) = 3 then planHand = i")
    a("    if handKind(i) = 1 and handCost(i) = 2 and needsChoice(i) = 0 then shieldHand = i")
    a("    if handKind(i) = 1 and handCost(i) = 4 then oozeHand = i")
    a("    i = i + 1")
    a("  wend")
    a("")
    a("  ' Our Primordial on the board and its ordinal among our minions.")
    a("  primBoard = -1")
    a("  primOrdinal = -1")
    a("  ownCount = 0")
    a("  b = 0")
    a("  while b < selfBoardSize")
    a("    if selfBoardHp(b) > 0 then")
    a("      if selfBoardPower(b) >= 6 and primBoard < 0 then")
    a("        primBoard = b")
    a("        primOrdinal = ownCount")
    a("      end if")
    a("      ownCount = ownCount + 1")
    a("    end if")
    a("    b = b + 1")
    a("  wend")
    a("")
    a("  ' The attacker's minions from a Bouncer's choice list, damage taken")
    a("  ' since our last turn, own turns since the Primordial was played, and")
    a("  ' whether our board was emptied on the opponents' turns.")
    a("  attackerMinions = 0")
    a("  if bouncerHand >= 0 then")
    a("    nChoices = choiceCount(bouncerHand)")
    a("    j = 0")
    a("    while j < nChoices")
    a("      if choiceKind(bouncerHand, j) = 3 and choiceOwner(bouncerHand, j) = prevPlayer then attackerMinions = attackerMinions + 1")
    a("      j = j + 1")
    a("    wend")
    a("  elseif viewOk = 1 then")
    a("    attackerMinions = view(prevPlayer)")
    a("  end if")
    a("  if turnNumber <> lockTurn then")
    a("    incoming = 0")
    a("    if lifeSeen = 1 then incoming = lastLife - selfLife")
    a("    wipeSeen = 0")
    a("    if selfBoardSize = 0 and lastSelfBoard >= 2 then wipeSeen = 1")
    a("    turnsSince = turnsSince + 1")
    a("    lockTurn = turnNumber")
    a("  end if")
    a("  lastLife = selfLife")
    a("  lifeSeen = 1")
    a("  lastSelfBoard = selfBoardSize")
    a("  bigVisible = 0")
    a("  if duelPhase = 1 then")
    a("    for b = 0 to eCount - 1")
    a("      if ePow(b) >= 10 then bigVisible = 1")
    a("    next b")
    a("  end if")
    a("")
    a("  wantReset = 0")
    a("  if primBoard >= 0 then")
    if R == 'alternate':
        a("    if turnsSince >= 2 then wantReset = 1")
    elif R == 'alternate_if_needed':
        a("    if turnsSince >= 2 and (attackerMinions >= 1 or selfBoardHp(primBoard) <= 7) then wantReset = 1")
    elif R == 'need':
        a("    coverable = bouncers - " + str(reserve))
        a("    if energy < coverable then coverable = energy")
        a("    if selfBoardHp(primBoard) <= 5 then wantReset = 1")
        a("    if attackerMinions > coverable then wantReset = 1")
        a("    if incoming >= 8 then wantReset = 1")
    elif R == 'eager':
        a("    if selfBoardHp(primBoard) <= 7 then wantReset = 1")
        a("    if attackerMinions >= 2 then wantReset = 1")
        a("    if incoming >= 5 then wantReset = 1")
    elif R == 'never':
        a("    wantReset = 0")
    a("  end if")
    a("")
    a("  ' Land the Primordial when none is on the board" + (", or as the reset." if S == 'reset' else "."))
    cond = "primBoard < 0" + (" or wantReset = 1" if S == 'reset' else "")
    a("  if primHand >= 0 and energy >= 8 and (" + cond + ") then")
    a("    PRINT \"turn\", turnNumber, \"mage primordial\"")
    a("    turnsSince = 0")
    a("    playCard(primHand)")
    a("    END")
    a("  end if")
    a("")
    a("  ' Reset: a Bouncer returns our own Primordial to hand; the replay")
    a("  ' follows on the next decision.")
    a("  if wantReset = 1 and primBoard >= 0 and primHand < 0 and bouncerHand >= 0 and energy >= 9 then")
    a("    seen = 0")
    a("    pick = -1")
    a("    nChoices = choiceCount(bouncerHand)")
    a("    j = 0")
    a("    while j < nChoices")
    a("      if choiceKind(bouncerHand, j) = 3 and choiceOwner(bouncerHand, j) = selfPlayer then")
    a("        if seen = primOrdinal then pick = j")
    a("        seen = seen + 1")
    a("      end if")
    a("      j = j + 1")
    a("    wend")
    a("    if pick >= 0 then")
    a("      PRINT \"turn\", turnNumber, \"mage reset\"")
    a("      playCardChoice(bouncerHand, pick)")
    a("      END")
    a("    end if")
    a("  end if")
    a("")
    a("  ' Locked: Bouncers on the attacker's minions beyond the reserve kept")
    a("  ' for the next reset, Oozification, then draw.")
    a("  if primBoard >= 0 then")
    a("    i = 0")
    a("    while i < handSize")
    a("      if canPlay(i) and handKind(i) = 0 and handCost(i) = 1 and handToughness(i) = 1 and bouncers > " + str(reserve) + " then")
    a("        nChoices = choiceCount(i)")
    a("        best = -1")
    a("        j = 0")
    a("        while j < nChoices")
    a("          if choiceKind(i, j) = 3 and choiceOwner(i, j) = prevPlayer then best = j")
    a("          j = j + 1")
    a("        wend")
    a("        if best >= 0 then")
    a("          playCardChoice(i, best)")
    a("          END")
    a("        end if")
    a("      end if")
    a("      i = i + 1")
    a("    wend")
    ooze_cond = "1" if O == 'any' else "(wipeSeen = 1 or bigVisible = 1)"
    a("    if oozeHand >= 0 and canPlay(oozeHand) and " + ooze_cond + " then")
    a("      nChoices = choiceCount(oozeHand)")
    a("      if duelPhase = 1 then")
    a("        pickVisible(oozeHand, -1, 2, 0)")
    a("        if pick >= 0 then")
    a("          playCardChoice(oozeHand, pick)")
    a("          END")
    a("        end if")
    a("      end if")
    a("      j = 0")
    a("      while j < nChoices")
    a("        if choiceKind(oozeHand, j) = 3 and choiceOwner(oozeHand, j) = prevPlayer then")
    a("          playCardChoice(oozeHand, j)")
    a("          END")
    a("        end if")
    a("        j = j + 1")
    a("      wend")
    a("    end if")
    a("    if planHand >= 0 and canPlay(planHand) and selfDeckSize > 2 then")
    a("      playCard(planHand)")
    a("      END")
    a("    end if")
    a("    END")
    a("  end if")
    a("")
    a("  ' No lock yet: survive and dig. Free cards first.")
    a("  i = 0")
    a("  while i < handSize")
    a("    if canPlay(i) and handCost(i) = 0 and needsChoice(i) = 0 then")
    a("      if handKind(i) = 2 or handKind(i) = 0 then")
    a("        playCard(i)")
    a("        END")
    a("      end if")
    a("    end if")
    a("    i = i + 1")
    a("  wend")
    study_ok = "1" if D != 'guard' else "primHand < 0"
    if D in ('study', 'guard'):
        a("  ' Study first while the deck lasts" + (", unless a Primordial is in hand." if D == 'guard' else "."))
        a("  if shieldHand >= 0 and canPlay(shieldHand) and selfDeckSize > 5 and energy > 2 and " + study_ok + " then")
        a("    playCard(shieldHand)")
        a("    END")
        a("  end if")
    if D == 'plan':
        a("  ' Plan first: it draws without discarding.")
        a("  if planHand >= 0 and canPlay(planHand) and selfDeckSize > 5 then")
        a("    playCard(planHand)")
        a("    END")
        a("  end if")
    a("  ' Bouncers only on the attacker's minions; in a final duel the next")
    a("  ' player's strongest visible minion.")
    a("  i = 0")
    a("  while i < handSize")
    a("    if canPlay(i) and handKind(i) = 0 and handCost(i) = 1 and handToughness(i) = 1 then")
    a("      nChoices = choiceCount(i)")
    a("      best = -1")
    a("      j = 0")
    a("      while j < nChoices")
    a("        if choiceKind(i, j) = 3 and choiceOwner(i, j) = prevPlayer then best = j")
    a("        j = j + 1")
    a("      wend")
    a("      if duelPhase = 1 and best >= 0 then")
    a("        pickVisible(i, -1, 2, 0)")
    a("        if pick >= 0 then best = pick")
    a("      end if")
    a("      if best >= 0 then")
    a("        playCardChoice(i, best)")
    a("        END")
    a("      end if")
    a("    end if")
    a("    i = i + 1")
    a("  wend")
    a("  ' Draws while the deck lasts.")
    a("  if planHand >= 0 and canPlay(planHand) and selfDeckSize > 5 then")
    a("    playCard(planHand)")
    a("    END")
    a("  end if")
    a("  if shieldHand >= 0 and canPlay(shieldHand) and selfDeckSize > 5 and " + study_ok + " then")
    a("    playCard(shieldHand)")
    a("    END")
    a("  end if")
    a("  ' Oozification on an attacker's minion" + (" when a Primordial is suspected." if O == 'reserve' else " with spare energy."))
    a("  if oozeHand >= 0 and canPlay(oozeHand) and " + ooze_cond + " then")
    a("    nChoices = choiceCount(oozeHand)")
    a("    if duelPhase = 1 then")
    a("      pickVisible(oozeHand, -1, 2, 0)")
    a("      if pick >= 0 then")
    a("        playCardChoice(oozeHand, pick)")
    a("        END")
    a("      end if")
    a("    end if")
    a("    j = 0")
    a("    while j < nChoices")
    a("      if choiceKind(oozeHand, j) = 3 and choiceOwner(oozeHand, j) = prevPlayer then")
    a("        playCardChoice(oozeHand, j)")
    a("        END")
    a("      end if")
    a("      j = j + 1")
    a("    wend")
    a("  end if")
    a("  END")
    a("end if")
    return '\n'.join(s)

variants = {
  'loop01_alt': ('alternate', 'study', 'any', 'reset', 1),
  'loop02_alt_plan': ('alternate', 'plan', 'any', 'reset', 1),
  'loop03_alt_guard': ('alternate', 'guard', 'reserve', 'hold', 1),
  'loop04_need': ('need', 'study', 'any', 'reset', 1),
  'loop05_need_guard': ('need', 'guard', 'reserve', 'hold', 1),
  'loop06_eager': ('eager', 'study', 'any', 'reset', 1),
  'loop07_eager_guard': ('eager', 'guard', 'reserve', 'hold', 1),
  'loop08_altneed': ('alternate_if_needed', 'study', 'any', 'reset', 1),
  'loop09_altneed_guard': ('alternate_if_needed', 'guard', 'reserve', 'hold', 1),
  'loop10_never_guard': ('never', 'guard', 'reserve', 'hold', 1),
  'loop11_alt_reserve2': ('alternate', 'study', 'any', 'reset', 2),
  'loop12_alt_plan_reserve0': ('alternate', 'plan', 'any', 'reset', 0),
}
for name, knobs in variants.items():
    open('trials/' + name + '.bas', 'w').write(head + '\n' + mage(*knobs) + '\n' + tail)
    print(name)
